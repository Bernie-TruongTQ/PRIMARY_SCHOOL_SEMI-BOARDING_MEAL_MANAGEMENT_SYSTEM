  'lunch',
  'dinner',
  'snack'
);

CREATE TYPE "participation_status_enum" AS ENUM (
  'pending',
  'recorded',
  'confirmed',
  'cancelled'
);

CREATE TYPE "participation_change_type_enum" AS ENUM (
  'status_update',
  'correction',
  'reschedule'
);

CREATE TYPE "demand_determination_method_enum" AS ENUM (
  'participation_based',
  'manual_forecast',
  'historical_average'
);

