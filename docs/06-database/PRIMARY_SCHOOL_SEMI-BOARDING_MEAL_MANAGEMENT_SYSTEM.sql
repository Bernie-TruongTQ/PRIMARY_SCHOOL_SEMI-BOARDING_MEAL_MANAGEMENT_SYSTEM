CREATE TABLE "users" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "full_name" varchar,
  "role" varchar
);

CREATE TABLE "meal_schedules" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_date" date,
  "meal_type" meal_type_enum,
  "menu_id" integer
);

CREATE TABLE "dishes" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar,
  "status" varchar
);

CREATE TABLE "ingredients" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar,
  "unit" varchar
);

CREATE TABLE "meal_registrations" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "student_id" integer,
  "meal_schedule_id" integer,
  "status" varchar
);

CREATE TABLE "meal_participations" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "student_id" integer NOT NULL,
  "meal_schedule_id" integer NOT NULL,
  "meal_registration_id" integer,
  "meal_date" date NOT NULL,
  "meal_type" meal_type_enum NOT NULL,
  "status" participation_status_enum NOT NULL DEFAULT 'pending',
  "recorded_by" integer,
  "recorded_at" datetime,
  "confirmed_by" integer,
  "confirmed_at" datetime,
  "notes" varchar,
  "created_at" datetime DEFAULT (now()),
  "updated_at" datetime
);

CREATE TABLE "meal_participation_changes" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_participation_id" integer NOT NULL,
  "change_type" participation_change_type_enum NOT NULL,
  "old_status" participation_status_enum,
  "new_status" participation_status_enum,
  "reason" varchar,
  "changed_by" integer NOT NULL,
  "changed_at" datetime DEFAULT (now())
);

CREATE TABLE "meal_demands" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_schedule_id" integer NOT NULL,
  "meal_date" date NOT NULL,
  "meal_type" meal_type_enum NOT NULL,
  "determined_quantity" integer NOT NULL,
  "determination_method" demand_determination_method_enum NOT NULL DEFAULT 'participation_based',
  "status" demand_status_enum NOT NULL DEFAULT 'draft',
  "determined_by" integer,
  "determined_at" datetime,
  "confirmed_by" integer,
  "confirmed_at" datetime,
  "created_at" datetime DEFAULT (now()),
  "updated_at" datetime
);

CREATE TABLE "meal_demand_dish_quantities" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_demand_id" integer NOT NULL,
  "dish_id" integer NOT NULL,
  "expected_quantity" decimal NOT NULL,
  "unit" varchar NOT NULL,
  "calculated_by" integer,
  "calculated_at" datetime DEFAULT (now())
);

CREATE TABLE "meal_demand_changes" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_demand_id" integer NOT NULL,
  "change_type" demand_change_type_enum NOT NULL,
  "old_quantity" integer,
  "new_quantity" integer,
  "reason" varchar,
  "changed_by" integer NOT NULL,
  "changed_at" datetime DEFAULT (now())
);

CREATE TABLE "meal_preparation_plans" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_demand_id" integer NOT NULL,
  "meal_schedule_id" integer NOT NULL,
  "planned_date" date NOT NULL,
  "meal_type" meal_type_enum NOT NULL,
  "status" prep_plan_status_enum NOT NULL DEFAULT 'planned',
  "planned_by" integer,
  "planned_at" datetime DEFAULT (now())
);

