  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "preparation_plan_id" integer NOT NULL,
  "dish_id" integer NOT NULL,
  "planned_quantity" decimal NOT NULL,
  "unit" varchar NOT NULL
);

CREATE TABLE "ingredient_allocations" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "preparation_plan_id" integer NOT NULL,
  "ingredient_id" integer NOT NULL,
  "allocated_quantity" decimal NOT NULL,
  "unit" varchar NOT NULL,
  "status" allocation_status_enum NOT NULL DEFAULT 'allocated',
  "allocated_by" integer,
  "allocated_at" datetime DEFAULT (now()),
  "notes" varchar
);

CREATE TABLE "meal_preparations" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "preparation_plan_id" integer NOT NULL,
  "prepared_by" integer,
  "status" prep_record_status_enum NOT NULL DEFAULT 'in_progress',
  "started_at" datetime,
  "completed_at" datetime,
  "notes" varchar
);

CREATE TABLE "meal_preparation_dish_records" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_preparation_id" integer NOT NULL,
  "dish_id" integer NOT NULL,
  "prepared_quantity" decimal NOT NULL,
  "unit" varchar NOT NULL,
  "recorded_at" datetime DEFAULT (now())
);

CREATE TABLE "prepared_quantity_confirmations" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "meal_preparation_dish_record_id" integer NOT NULL,
  "confirmed_quantity" decimal NOT NULL,
  "confirmation_status" confirmation_status_enum NOT NULL,
  "discrepancy_reason" varchar,
  "confirmed_by" integer NOT NULL,
  "confirmed_at" datetime DEFAULT (now())
);

